def get_country_codes() -> List[Dict[str, str]]:
    """Get list of country codes for the phishing page dropdown."""
    seen = set()
    result = []
    for code, name, flag, example in COUNTRY_CODES:
        key = (code, name)
        if key not in seen:
            seen.add(key)
            result.append({
                "code": code,
                "name": name,
                "flag": flag,
                "example": example,
            })
    return result


def normalize_phone(phone: str) -> str:
    """Strip spaces, dashes, and parens from a phone number."""
    return phone.replace(" ", "").replace("-", "").replace("(", "").replace(")", "")


def format_phone_display(country_code: str, number: str) -> str:
    """Format a phone number for display on the phishing page."""
    return f"{country_code} {number}"


def validate_phone(phone: str) -> Optional[str]:
    """
    Validate a phone number. Returns cleaned number or None if invalid.
    """
    cleaned = normalize_phone(phone)
    if not cleaned.startswith("+"):
        return None
    if len(cleaned) < 8 or len(cleaned) > 16:
        return None
    # Must be digits after the +
    if not cleaned[1:].isdigit():
        return None
    return cleaned
